"""동작 확인용 샘플 약관 PDF 를 만든다.

    python scripts/make_sample_terms_pdf.py data/terms/sample_terms.pdf

reportlab 의 내장 한국어 CID 폰트를 쓰므로 별도 폰트 파일이 필요 없다.
"""

from __future__ import annotations

import sys
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.cidfonts import UnicodeCIDFont
from reportlab.pdfgen import canvas

FONT = "HYSMyeongJo-Medium"

TERMS = """차차 서비스 이용약관

제1장 총칙

제1조(목적)
이 약관은 주식회사 차차(이하 "회사"라 합니다)가 제공하는 차차 서비스(이하 "서비스")의
이용과 관련하여 회사와 이용자 간의 권리, 의무 및 책임사항, 이용조건과 절차 등 기본적인
사항을 규정함을 목적으로 합니다.

제2조(정의)
① 이 약관에서 사용하는 용어의 정의는 다음과 같습니다.
1. "서비스"란 회사가 유무선 정보통신설비를 이용하여 제공하는 모든 서비스를 말합니다.
2. "회원"이란 이 약관에 동의하고 회사와 이용계약을 체결한 자를 말합니다.
가. 개인회원: 개인이 자신의 명의로 가입한 회원
나. 기업회원: 사업자등록번호로 가입한 회원
3. "유료서비스"란 회원이 대금을 지급하고 이용하는 서비스를 말합니다.
② 이 약관에서 정하지 아니한 용어의 정의는 관계 법령 및 서비스별 안내에 따릅니다.

제3조(약관의 명시와 개정)
① 회사는 이 약관의 내용을 회원이 쉽게 알 수 있도록 서비스 초기 화면에 게시합니다.
② 회사는 약관의 규제에 관한 법률 등 관계 법령을 위배하지 않는 범위에서 이 약관을
개정할 수 있습니다.
③ 회사가 약관을 개정할 경우 적용일자 및 개정사유를 명시하여 적용일자 7일 전부터
공지합니다. 다만 회원에게 불리한 개정의 경우에는 30일 전부터 공지하고 전자우편 등으로
개별 통지합니다.
④ 회원이 개정약관의 적용에 동의하지 않는 경우 이용계약을 해지할 수 있습니다.

제2장 이용계약

제4조(이용계약의 성립)
① 이용계약은 회원이 되고자 하는 자가 약관의 내용에 동의한 후 이용신청을 하고 회사가
이를 승낙함으로써 성립합니다.
② 회사는 다음 각 호에 해당하는 신청에 대하여는 승낙을 하지 않거나 사후에 이용계약을
해지할 수 있습니다.
1. 타인의 명의를 이용하여 신청한 경우
2. 허위의 정보를 기재하거나 회사가 요구하는 내용을 기재하지 않은 경우
3. 만 14세 미만의 아동이 법정대리인의 동의 없이 신청한 경우

제5조(회원정보의 변경)
회원은 개인정보 관리화면을 통하여 자신의 정보를 열람하고 수정할 수 있습니다. 회원은
이용신청 시 기재한 사항이 변경되었을 경우 지체 없이 이를 수정하여야 하며, 수정하지
않아 발생한 불이익에 대하여 회사는 책임지지 않습니다.

제3장 유료서비스와 결제

제12조(청약철회 및 환불)
① 회원은 유료서비스 결제일로부터 7일 이내에 청약을 철회할 수 있습니다. 다만 다음 각
호의 어느 하나에 해당하는 경우에는 청약철회가 제한됩니다.
1. 회원의 책임 있는 사유로 재화 등이 멸실되거나 훼손된 경우
2. 회원의 사용 또는 일부 소비로 재화 등의 가치가 현저히 감소한 경우
3. 디지털 콘텐츠의 제공이 개시된 경우. 다만 가분적 콘텐츠로 구성된 계약의 경우
제공이 개시되지 아니한 부분에 대하여는 그러하지 아니합니다.
② 회사는 청약철회의 의사표시를 받은 날부터 3영업일 이내에 이미 지급받은 대금을
환급합니다.
③ 회사가 제2항의 기간을 초과하여 환급을 지연한 경우에는 지연기간에 대하여 관계
법령에서 정한 지연배상금을 지급합니다.
④ 회원이 신용카드로 결제한 경우 회사는 지체 없이 결제업자에게 대금 청구의 정지 또는
취소를 요청합니다.

제12조의2(정기결제 상품의 중도 해지)
① 정기결제 상품을 이용하는 회원은 언제든지 다음 결제일 전까지 해지를 신청할 수
있으며, 해지 효력은 해당 결제 주기 종료일에 발생합니다.
② 회사는 이미 경과한 이용기간에 해당하는 금액과 위약금을 공제한 잔액을 환급합니다.

제13조(과오금의 환급)
회사는 과오금이 발생한 경우 그 과오금 전액을 환급합니다. 다만 회원의 책임 있는 사유로
과오금이 발생한 경우에는 환급에 소요되는 비용을 회원이 부담합니다.

제4장 책임과 의무

제20조(회사의 의무)
① 회사는 관계 법령과 이 약관이 금지하는 행위를 하지 않으며 계속적이고 안정적으로
서비스를 제공하기 위하여 최선을 다합니다.
② 회사는 회원의 개인정보를 본인의 동의 없이 제3자에게 제공하지 않습니다.

제21조(면책조항)
① 회사는 천재지변, 디도스 공격, 기간통신사업자의 회선 장애 등 불가항력으로 인하여
서비스를 제공할 수 없는 경우에는 책임이 면제됩니다.
② 회사는 회원의 귀책사유로 인한 서비스 이용 장애에 대하여 책임을 지지 않습니다.
③ 회사는 회원이 서비스를 통해 얻은 정보로 인해 입은 손해에 대하여 책임을 지지
않습니다. 다만 회사의 고의 또는 중대한 과실이 있는 경우에는 그러하지 아니합니다.

제22조(분쟁의 해결)
① 회사와 회원 간에 발생한 분쟁은 상호 협의하여 해결함을 원칙으로 합니다.
② 협의가 이루어지지 않는 경우 소송은 민사소송법상의 관할 법원에 제기합니다.

부칙 (2026. 1. 1.)
이 약관은 2026년 1월 1일부터 시행합니다. 종전의 약관은 이 약관으로 대체됩니다.
"""


def build(path: Path) -> Path:
    pdfmetrics.registerFont(UnicodeCIDFont(FONT))
    path.parent.mkdir(parents=True, exist_ok=True)

    width, height = A4
    margin_x, top, bottom = 60, height - 70, 70
    leading = 17

    pdf = canvas.Canvas(str(path), pagesize=A4)
    page_no = 1
    y = top

    def new_page() -> float:
        nonlocal page_no
        # 머리말/꼬리말: 로더가 이런 반복 요소를 제거하는지 확인하는 용도이기도 하다
        pdf.setFont(FONT, 8)
        pdf.drawString(margin_x, height - 40, "차차 서비스 이용약관")
        pdf.drawCentredString(width / 2, 40, f"- {page_no} -")
        pdf.setFont(FONT, 10.5)
        page_no += 1
        return top

    y = new_page()
    for line in TERMS.splitlines():
        if y < bottom:
            pdf.showPage()
            y = new_page()
        if line.strip():
            pdf.drawString(margin_x, y, line)
        y -= leading

    pdf.showPage()
    pdf.save()
    return path


if __name__ == "__main__":
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "data/terms/sample_terms.pdf")
    print(f"생성: {build(target)}")
