"""담보(급부) 범위 — 약관이 답할 수 있는 것과 없는 것의 경계.

**약관에 담보가 있다는 것과, 그 계약이 그 담보에 가입했다는 것은 다르다.**

하나의 약관에는 그 상품에서 **가입할 수 있는 담보가 전부** 들어 있다.
골절진단비 · 수술비 · 입원일당 · 후유장해 … 실제 계약은 그중 일부만 가입한다.
따라서 약관에서 골절진단비 조항을 찾았다고 「지급됩니다」라고 답하면,
그 특약에 가입하지 않은 계약에는 틀린 답이 된다.

계약별 가입 담보는 계약 정보(Cloud DATA)에 있고 **이번 범위 밖**이다.
그러므로 약관 기반 답변은 언제나 조건부다.

  「해당 담보에 가입되어 있다면」 — 이 전제를 빠뜨리면 안 된다.

또 하나. FA가 담보를 특정하지 않고 상황만 말하는 경우가 많다.

  「이 사고로 뭐 받을 수 있어요?」

이때 담보 하나만 답하면 누락이 생긴다. 골절 사고 하나에도
골절진단비 · 상해입원일당 · 수술비 · 후유장해가 동시에 걸릴 수 있다.
**해당 가능한 담보를 모두 늘어놓는 것**이 FA에게 실제로 필요한 답이다.
"""

from __future__ import annotations

from enum import Enum


class BenefitScope(Enum):
    """답변에서 담보를 어떻게 다룰지."""

    SPECIFIC = "specific"
    """FA가 담보를 지목했다. 그 담보의 지급사유 · 면책을 중심으로 답한다.
    예) 「골절진단비 나오나요?」"""

    ENUMERATE = "enumerate"
    """담보가 지목되지 않았다. 해당 상황에 걸릴 수 있는 담보를 **모두** 제시한다.
    예) 「골절됐는데 뭐 받을 수 있어요?」

    하나만 답하면 FA가 청구 가능한 담보를 놓친다."""


#: 약관 기반 지급 답변에 반드시 붙는 전제.
#: 계약별 가입 담보는 Cloud DATA(범위 밖)이므로 우리는 확인할 수 없다.
ENROLLMENT_CAVEAT = "약관상 담보 기준입니다. 실제 지급은 해당 담보에 가입한 계약에 한하므로, 가입 담보를 함께 확인해 주세요."

#: 담보를 늘어놓을 때 덧붙이는 안내.
ENUMERATE_HINT = "이 상품 약관에 있는 담보 기준이며, 계약마다 가입한 담보가 다릅니다."


def scope_for(benefit_mentioned: str | None) -> BenefitScope:
    """FA가 담보를 지목했는지로 답변 범위를 정한다."""
    return BenefitScope.SPECIFIC if benefit_mentioned else BenefitScope.ENUMERATE
